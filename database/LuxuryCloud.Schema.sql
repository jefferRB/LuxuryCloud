CREATE   PROCEDURE ObtenerCitasProximas
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        Nombre,
        CorreoElectronico,
        NumeroTelefono,
        FechaUltimaVisita,
        FrecuenciaVisita,
        DATEADD(DAY, FrecuenciaVisita, FechaUltimaVisita) AS FechaProximaVisita
    FROM Clientes
    WHERE
        DATEADD(DAY, FrecuenciaVisita, FechaUltimaVisita) =
		CAST(DATEADD(DAY, 3, GETDATE()) AS DATE)
END;
GO

